    def convert_id_to_char(self, ys):
        all_seqs = []
        for i, y in enumerate(ys):
            y = ys[i]
            seq_true = []
            for idx in y:
                idx = int(idx)
                seq_true.append(self.token_list[int(idx)])
            seq_chars = "".join(seq_true)
            all_seqs.append(seq_chars)

        return all_seqs

